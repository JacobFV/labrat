#!/usr/bin/env python3
"""Generate firmware/include/robot_config.h from config/robot.json.

robot.json is the single source of truth for geometry, joint map, pins and link
strings. The firmware compiles these values in as *defaults*; calibration and
geometry can later be overridden at runtime and persisted in NVS.

Usage:
    python3 tools/gen_config.py            # (re)write include/robot_config.h
    python3 tools/gen_config.py --check    # exit 1 if the header is stale

The native unit test `test_config` re-parses robot.json at test time and
asserts every generated constant matches, so a stale header fails CI.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW_DIR = HERE.parent
DEFAULT_JSON = FW_DIR.parent / "config" / "robot.json"
DEFAULT_OUT = FW_DIR / "include" / "robot_config.h"

ARM_JOINT_SUFFIXES = ("YAW", "SHOULDER", "ELBOW")


def fnum(v: float) -> str:
    """Format a number as a C++ float literal."""
    v = float(v)
    if v == int(v):
        return f"{int(v)}.0f"
    return f"{repr(v)}f"


def cstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_pwm(desc: str) -> tuple[int, float]:
    m_addr = re.search(r"0x([0-9A-Fa-f]{2})", desc)
    m_osc = re.search(r"([0-9.]+)\s*MHz", desc)
    if not m_addr or not m_osc:
        raise SystemExit(f"cannot parse PCA9685 address/oscillator from electronics.pwm: {desc!r}")
    return int(m_addr.group(1), 16), float(m_osc.group(1)) * 1e6


def generate(robot: dict, src_bytes: bytes) -> str:
    joints = robot["joints"]
    names = list(joints.keys())
    arms = robot["arms"]
    arm_names = list(arms.keys())
    if arm_names != ["L", "R"]:
        raise SystemExit(f"expected arms L and R in that order, got {arm_names}")
    for a in arm_names:
        for suf in ARM_JOINT_SUFFIXES:
            if f"{a}_{suf}" not in joints:
                raise SystemExit(f"missing joint {a}_{suf}")
    for n in ("NECK_PAN", "NECK_TILT"):
        if n not in joints:
            raise SystemExit(f"missing joint {n}")

    servo = robot["servo"]
    tool = robot["tool"]
    link = robot["link"]
    aoa = link["aoa"]
    el = robot["electronics"]
    pins = el["pins"]
    div = el["dividers"]
    neck = robot["neck"]
    dev = robot["default_device"]
    pca_addr, pca_osc = parse_pwm(el["pwm"])
    sha = hashlib.sha256(src_bytes).hexdigest()

    L = []
    w = L.append
    w("// AUTO-GENERATED by firmware/tools/gen_config.py from config/robot.json.")
    w("// DO NOT EDIT BY HAND. Re-run: python3 firmware/tools/gen_config.py")
    w(f"// robot.json sha256: {sha}")
    w("#pragma once")
    w("")
    w("#include <stdint.h>")
    w("")
    w("namespace tappet {")
    w("namespace cfg {")
    w("")
    w(f"constexpr const char* ROBOT_NAME = {cstr(robot['name'])};")
    w(f"constexpr const char* ROBOT_VERSION = {cstr(robot['version'])};")
    w(f"constexpr const char* ROBOT_JSON_SHA256 = {cstr(sha)};")
    w("")
    w("// ---- servo electrical mapping ----")
    w(f"constexpr float SERVO_PWM_HZ = {fnum(servo['pwm_hz'])};")
    w(f"constexpr float SERVO_US_MIN = {fnum(servo['us_min'])};")
    w(f"constexpr float SERVO_US_MAX = {fnum(servo['us_max'])};")
    w(f"constexpr float SERVO_DEG_RANGE = {fnum(servo['deg_range'])};")
    w("")
    w("// ---- joints (index order = robot.json order) ----")
    w(f"constexpr int NUM_JOINTS = {len(names)};")
    w("enum JointId : uint8_t {")
    for i, n in enumerate(names):
        w(f"  J_{n} = {i},")
    w("};")
    w("")
    w("struct JointDefault {")
    w("  const char* name;")
    w("  int ch;")
    w("  float gear;")
    w("  int dir;")
    w("  float s_zero, neutral, min, max, home, park, max_vel;")
    w("};")
    w("")
    w("constexpr JointDefault JOINTS[NUM_JOINTS] = {")
    for n in names:
        j = joints[n]
        w(
            f"  {{{cstr(n)}, {int(j['ch'])}, {fnum(j['gear'])}, {int(j['dir'])}, "
            f"{fnum(j['s_zero'])}, {fnum(j['neutral'])}, {fnum(j['min'])}, {fnum(j['max'])}, "
            f"{fnum(j['home'])}, {fnum(j['park'])}, {fnum(j['max_vel'])}}},"
        )
    w("};")
    w("")
    w("// ---- arms ----")
    w("constexpr int NUM_ARMS = 2;")
    w("enum ArmId : uint8_t { ARM_L = 0, ARM_R = 1 };")
    w("constexpr const char* ARM_NAMES[NUM_ARMS] = {\"L\", \"R\"};")
    w("// joint indices [arm][yaw, shoulder, elbow]")
    w("constexpr uint8_t ARM_JOINTS[NUM_ARMS][3] = {")
    for a in arm_names:
        idx = ", ".join(f"J_{a}_{s}" for s in ARM_JOINT_SUFFIXES)
        w(f"  {{{idx}}},")
    w("};")
    w("constexpr uint8_t NECK_JOINTS[2] = {J_NECK_PAN, J_NECK_TILT};")
    w("")
    w("struct ArmDefault {")
    w("  float base_x, base_y, shoulder_h, r0, L1, L2, tool_dx, tool_dz;")
    w("};")
    w("constexpr ArmDefault ARMS[NUM_ARMS] = {")
    for a in arm_names:
        g = arms[a]
        vals = ", ".join(fnum(g[k]) for k in ("base_x", "base_y", "shoulder_h", "r0", "L1", "L2", "tool_dx", "tool_dz"))
        w(f"  {{{vals}}},  // {a}")
    w("};")
    w("")
    w(f"constexpr float LINKAGE_REL_MIN = {fnum(robot['linkage']['rel_min'])};")
    w(f"constexpr float LINKAGE_REL_MAX = {fnum(robot['linkage']['rel_max'])};")
    w("")
    w("// ---- tool / stylus ----")
    w(f"constexpr float TOOL_STYLUS_TRAVEL = {fnum(tool['stylus_travel'])};")
    w(f"constexpr float TOOL_DEFAULT_PRESS_MM = {fnum(tool['default_press_mm'])};")
    w(f"constexpr float TOOL_DEFAULT_APPROACH_MM = {fnum(tool['default_approach_mm'])};")
    w(f"constexpr float TOOL_DEFAULT_HOLD_MS = {fnum(tool['default_hold_ms'])};")
    w(f"constexpr float TOOL_TIP_DIAMETER = {fnum(tool['tip_diameter'])};")
    w(f"constexpr float DEFAULT_SURFACE_Z = {fnum(dev['surface_z'])};")
    w("")
    w("// ---- neck poses ----")
    w(f"constexpr float NECK_LOOK_AT_TRAY_PAN = {fnum(neck['look_at_tray']['pan'])};")
    w(f"constexpr float NECK_LOOK_AT_TRAY_TILT = {fnum(neck['look_at_tray']['tilt'])};")
    w(f"constexpr float NECK_LOOK_AT_USER_PAN = {fnum(neck['look_at_user']['pan'])};")
    w(f"constexpr float NECK_LOOK_AT_USER_TILT = {fnum(neck['look_at_user']['tilt'])};")
    w("")
    w("// ---- electronics ----")
    w(f"constexpr uint8_t PCA9685_I2C_ADDR = 0x{pca_addr:02X};")
    w(f"constexpr float PCA9685_OSC_HZ = {fnum(pca_osc)};")
    for k, v in pins.items():
        w(f"constexpr int PIN_{k} = {int(v)};")
    for k, d in div.items():
        w(f"constexpr float DIV_{k}_R_TOP = {fnum(d['r_top'])};")
        w(f"constexpr float DIV_{k}_R_BOT = {fnum(d['r_bot'])};")
    w("")
    w("// ---- link ----")
    w(f"constexpr uint32_t UART_BAUD = {int(link['uart_baud'])};")
    w(f"constexpr uint32_t WATCHDOG_MS = {int(link['watchdog_ms'])};")
    w(f"constexpr uint16_t SIM_TCP_PORT = {int(link['sim_tcp_port'])};")
    w(f"constexpr uint16_t WEB_PORT = {int(link['web_port'])};")
    for k in ("manufacturer", "model", "description", "version", "uri", "serial"):
        w(f"constexpr const char* AOA_{k.upper()} = {cstr(aoa[k])};")
    w("// AOA SEND_STRING order (wIndex 0..5)")
    w("constexpr const char* AOA_STRINGS[6] = {AOA_MANUFACTURER, AOA_MODEL, AOA_DESCRIPTION,")
    w("                                        AOA_VERSION, AOA_URI, AOA_SERIAL};")
    w("")
    w("}  // namespace cfg")
    w("}  // namespace tappet")
    w("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", type=Path, default=DEFAULT_JSON)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="verify the header is up to date")
    args = ap.parse_args()

    src = args.json.read_bytes()
    text = generate(json.loads(src), src)
    if args.check:
        cur = args.out.read_text() if args.out.exists() else ""
        if cur != text:
            print(f"{args.out} is stale; run tools/gen_config.py", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
